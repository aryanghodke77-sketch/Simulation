"""Protocol event sequencing helpers.

Consumes protocol events generated by the simulator and produces an ordered,
step-friendly sequence suitable for step-by-step visualization.
"""
from __future__ import annotations

from typing import List

from network_lab.core.protocols import ProtocolEvent


def sorted_events(events: List[ProtocolEvent]) -> List[ProtocolEvent]:
    return sorted(events, key=lambda e: (e.timestamp, e.packet_id))


def step_events(events: List[ProtocolEvent]) -> List[List[ProtocolEvent]]:
    """Group events into steps for stepwise visualization.

    Heuristic: group by timestamp proximity (within 0.005 simulated seconds)
    and packet_id so a single packet's SYN/SYN-ACK/ACK/DATA can be shown
    together or progressively.
    """
    if not events:
        return []

    ordered = sorted_events(events)
    steps: List[List[ProtocolEvent]] = []
    current_step: List[ProtocolEvent] = []
    current_time = ordered[0].timestamp

    for ev in ordered:
        if abs(ev.timestamp - current_time) > 0.005 and current_step:
            steps.append(current_step)
            current_step = []
            current_time = ev.timestamp
        current_step.append(ev)

    if current_step:
        steps.append(current_step)

    return steps
